package com.vitorpamplona.quartz.utils

/**
 * Marks a declaration that is public only so other Quartz modules, and their tests, can reach
 * it across a module boundary. It is not part of Quartz's API: it can change or disappear in
 * any release.
 */
@RequiresOptIn(
    message = "Internal to Quartz: public only so Quartz's own modules can share it. It may change without notice.",
    level = RequiresOptIn.Level.ERROR,
)
@Retention(AnnotationRetention.BINARY)
@Target(
    AnnotationTarget.CLASS,
    AnnotationTarget.FUNCTION,
    AnnotationTarget.PROPERTY,
    AnnotationTarget.CONSTRUCTOR,
    AnnotationTarget.TYPEALIAS,
)
annotation class InternalQuartzApi
