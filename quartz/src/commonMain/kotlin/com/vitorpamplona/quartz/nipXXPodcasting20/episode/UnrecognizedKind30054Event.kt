package com.vitorpamplona.quartz.nipXXPodcasting20.episode

import androidx.compose.runtime.Immutable
import com.vitorpamplona.quartz.drss.listenProgress.DrssListenProgressEvent
import com.vitorpamplona.quartz.nip01Core.core.BaseAddressableEvent
import com.vitorpamplona.quartz.nip01Core.core.HexKey
import com.vitorpamplona.quartz.nip01Core.core.UnrecognizedShape

/**
 * A kind-30054 event that is neither a Podcasting-2.0 [Podcasting20EpisodeEvent] nor drss.io's
 * legacy [DrssListenProgressEvent], the two formats published on this number. Still addressable, so stores
 * replace and delete it by `d`; not a SearchableEvent, so it is never indexed.
 */
@Immutable
class UnrecognizedKind30054Event(
    id: HexKey,
    pubKey: HexKey,
    createdAt: Long,
    tags: Array<Array<String>>,
    content: String,
    sig: HexKey,
) : BaseAddressableEvent(id, pubKey, createdAt, Podcasting20EpisodeEvent.KIND, tags, content, sig),
    UnrecognizedShape
