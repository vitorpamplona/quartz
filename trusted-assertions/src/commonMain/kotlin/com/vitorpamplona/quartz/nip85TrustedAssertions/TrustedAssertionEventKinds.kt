package com.vitorpamplona.quartz.nip85TrustedAssertions

import com.vitorpamplona.quartz.nip85TrustedAssertions.addressables.AddressableAssertionEvent
import com.vitorpamplona.quartz.nip85TrustedAssertions.events.EventAssertionEvent
import com.vitorpamplona.quartz.nip85TrustedAssertions.externalIds.ExternalIdAssertionEvent
import com.vitorpamplona.quartz.nip85TrustedAssertions.list.TrustProviderListEvent
import com.vitorpamplona.quartz.nip85TrustedAssertions.users.UserAssertionEvent
import com.vitorpamplona.quartz.utils.EventKindProvider
import com.vitorpamplona.quartz.utils.EventKindRegistry

/** Registers the event classes of the `quartz-trusted-assertions` module with [com.vitorpamplona.quartz.utils.EventFactory]. */
object TrustedAssertionEventKinds : EventKindProvider {
    override fun registerKinds(registry: EventKindRegistry) {
        registry.register(UserAssertionEvent.KIND, ::UserAssertionEvent)
        registry.register(EventAssertionEvent.KIND, ::EventAssertionEvent)
        registry.register(AddressableAssertionEvent.KIND, ::AddressableAssertionEvent)
        registry.register(ExternalIdAssertionEvent.KIND, ::ExternalIdAssertionEvent)
        registry.register(TrustProviderListEvent.KIND, ::TrustProviderListEvent)
    }
}
